/* eslint-env node */
import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

const admin = "11111111-1111-4111-8111-111111111111";
const worker = "22222222-2222-4222-8222-222222222222";
const key = "33333333-3333-4333-8333-333333333333";
const project = {
  address: "123 Example St",
  work_order_number: "WO-1",
  date: "2026-10-17",
  total_amount: 0,
  project_type: "Address",
  files: ["original.pdf"],
};
const scan = {
  reviewed: true,
  original: { schema_version: "4.0" },
  reviewed_rows: [
    {
      id: "i1-r1",
      category: "labor",
      import_as_work: true,
      name: "Installation",
      amount: 0,
      quantity: 10,
      unit: "SF",
      notes: "Do not silicone.",
    },
    {
      id: "i1-r2",
      category: "material",
      import_as_work: false,
      name: "LVP",
      amount: 50,
    },
  ],
  date_end: "2026-10-18",
};

test("database import is atomic, idempotent, access-controlled and retains scan data", async (t) => {
  const db = new PGlite();
  t.after(() => db.close());
  await db.exec(`
    create role anon; create role authenticated;
    create schema auth;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true),'')::uuid $$;
    create table public.profiles(id uuid primary key,role text);
    create table public.addresses(id bigint generated by default as identity primary key,address text,work_order_number text,date date,total_amount numeric,store_id bigint,builder_id bigint,status text,project_type text,service_time time,original_photo_url text,ai_translation text,files text[],is_deleted boolean default false);
    create table public.work_type_templates(id bigint generated by default as identity primary key,name text not null);
    create table public.work_types(id bigint generated by default as identity primary key,address_id bigint references public.addresses(id),work_type_template_id bigint references public.work_type_templates(id),payment_amount numeric,person_id bigint,notes text);
    insert into auth.users values('${admin}'),('${worker}');
    insert into public.profiles values('${admin}','admin'),('${worker}','worker');
    grant usage on schema public,auth to authenticated;
    grant select,insert,update,delete on all tables in schema public to authenticated;
    grant usage,select on all sequences in schema public to authenticated;
    alter table public.addresses enable row level security;
    create policy admin_addresses on public.addresses to authenticated using(exists(select 1 from public.profiles where id=auth.uid() and role='admin')) with check(exists(select 1 from public.profiles where id=auth.uid() and role='admin'));
  `);
  const migration = await readFile(
    new URL(
      "../supabase/migrations/20261017195000_reviewed_ocr_import.sql",
      import.meta.url,
    ),
    "utf8",
  );
  await db.exec(migration);
  await db.exec(migration);
  await db.exec(`set role authenticated; set request.jwt.claim.sub='${admin}'`);
  const save = (body = scan, importKey = key, bodyProject = project) =>
    db.query(
      "select public.import_reviewed_work_order($1::jsonb,$2::jsonb,$3::uuid,false) as result",
      [JSON.stringify(bodyProject), JSON.stringify(body), importKey],
    );
  const created = await save();
  assert.equal(created.rows[0].result.work_items, 1);
  assert.equal((await save()).rows[0].result.already_imported, true);
  assert.equal(
    (await db.query("select count(*) as count from public.addresses")).rows[0]
      .count,
    1,
  );
  const work = (await db.query("select * from public.work_types")).rows[0];
  assert.equal(work.payment_amount, "0");
  assert.equal(work.notes, "Do not silicone.");
  assert.equal(work.ai_source.quantity, 10);
  const saved = (
    await db.query("select ai_scan,total_amount from public.addresses")
  ).rows[0];
  assert.equal(saved.total_amount, "0");
  assert.equal(saved.ai_scan.reviewed_rows.length, 2);
  assert.equal(saved.ai_scan.reviewed_by, admin);
  await assert.rejects(
    save(scan, "44444444-4444-4444-8444-444444444444"),
    /already exists/,
  );
  const bad = {
    ...scan,
    reviewed_rows: [
      scan.reviewed_rows[0],
      { ...scan.reviewed_rows[1], import_as_work: true },
    ],
  };
  await assert.rejects(
    save(bad, "55555555-5555-4555-8555-555555555555", {
      ...project,
      work_order_number: "WO-BAD",
    }),
    /Only labor/,
  );
  assert.equal(
    (await db.query("select count(*) as count from public.addresses")).rows[0]
      .count,
    1,
  );
  assert.equal(
    (await db.query("select count(*) as count from public.work_types")).rows[0]
      .count,
    1,
  );
  for (let i = 0; i < 10; i++)
    assert.equal(
      (await db.query("select public.consume_ocr_budget(10) as allowed"))
        .rows[0].allowed,
      true,
    );
  assert.equal(
    (await db.query("select public.consume_ocr_budget(1) as allowed")).rows[0]
      .allowed,
    false,
  );
  await db.exec(`set request.jwt.claim.sub='${worker}'`);
  await assert.rejects(save(), /Only administrators/);
  await assert.rejects(
    db.query("select public.consume_ocr_budget(1)"),
    /Only administrators/,
  );
});
